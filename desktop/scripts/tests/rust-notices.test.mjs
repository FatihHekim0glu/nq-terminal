// Born-failing tests for desktop/scripts/rust-notices.mjs (D7.4): the Cargo packages' notices file and the check that fails
// when it no longer matches Cargo.lock. Run: node --test desktop/scripts/tests
// No test runs cargo: the lockfiles are small fixtures, and the licence files are made in a scratch folder.
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { after, test } from 'node:test'
import { fileURLToPath } from 'node:url'
import {
  ROOT_CRATE, WEBVIEW2_LOADER, buildPackages, checkRustNotices, collectCrate, lockedCrates, renderRustNotices,
} from '../rust-notices.mjs'

const SCRIPT = fileURLToPath(new URL('../rust-notices.mjs', import.meta.url))
const TAURI = fileURLToPath(new URL('../../src-tauri/', import.meta.url))
const REAL_LOCK = path.join(TAURI, 'Cargo.lock')
const REAL_NOTICES = path.join(TAURI, 'THIRD_PARTY_NOTICES.txt')

const scratch = fs.mkdtempSync(path.join(process.env.TEMP ?? os.tmpdir(), 'rust-notices-test-'))
after(() => fs.rmSync(scratch, { recursive: true, force: true }))

const lock = (rootVersion, extra = '') => `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "adler2"
version = "2.0.1"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "320119579fcad9c21884f5c4861d16174d0e06250625266f50fe6898340abefa"

[[package]]
name = "nq-lab-terminal"
version = "${rootVersion}"
dependencies = [
 "adler2",
 "serde",
]

[[package]]
name = "serde"
version = "1.0.228"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "9a8e94ea7f378bd32cbbd37198a4a91436180c5bb472411e48b5ec2e2124ae9e"
${extra}`

const EXTRA_CRATE = `
[[package]]
name = "zeroize"
version = "1.8.1"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "ced3678a2879b30306d323f4542626697a464a97c0a07c9aebf7ebca65cd4dde"
`

const record = (name, version) => ({ name, version, license: 'MIT OR Apache-2.0', repository: '', texts: ['MIT text'], note: '' })
const render = (lockText) => renderRustNotices(lockedCrates(lockText).map((c) => record(c.name, c.version)))

test('lockedCrates lists the registry crates and skips the root crate', () => {
  assert.deepEqual(lockedCrates(lock('0.3.3')), [
    { name: 'adler2', version: '2.0.1' },
    { name: 'serde', version: '1.0.228' },
  ])
  assert.equal(ROOT_CRATE, 'nq-lab-terminal')
})

test('lockedCrates skips any crate with no source (a path crate of this repository), not only the root by name', () => {
  const text = lock('0.3.3', '\n[[package]]\nname = "local-helper"\nversion = "0.1.0"\n')
  assert.deepEqual(lockedCrates(text).map((c) => c.name), ['adler2', 'serde'])
})

test('lockedCrates keeps two versions of one crate as two entries', () => {
  const text = lock('0.3.3', '\n[[package]]\nname = "serde"\nversion = "0.9.0"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n')
  assert.deepEqual(lockedCrates(text).filter((c) => c.name === 'serde').map((c) => c.version).sort(), ['0.9.0', '1.0.228'])
})

test('notices written from a lockfile pass the check against it', () => {
  assert.deepEqual(checkRustNotices(lock('0.3.3'), render(lock('0.3.3'))), { ok: true, missing: [], extra: [] })
})

test('born failing: a lockfile crate missing from the notices fails, and names it', () => {
  const result = checkRustNotices(lock('0.3.3', EXTRA_CRATE), render(lock('0.3.3')))
  assert.equal(result.ok, false)
  assert.deepEqual(result.missing, ['zeroize 1.8.1'])
})

test('a crate the lockfile no longer has but the notices still name fails', () => {
  const result = checkRustNotices(lock('0.3.3'), render(lock('0.3.3', EXTRA_CRATE)))
  assert.equal(result.ok, false)
  assert.deepEqual(result.extra, ['zeroize 1.8.1'])
})

test('a dependency version change fails', () => {
  const bumped = lock('0.3.3').replace('1.0.228', '1.0.229')
  const result = checkRustNotices(bumped, render(lock('0.3.3')))
  assert.deepEqual(result, { ok: false, missing: ['serde 1.0.229'], extra: ['serde 1.0.228'] })
})

test('born failing: a changed root crate version alone does not fail (bump-version.ps1 rewrites that Cargo.lock entry)', () => {
  const notices = render(lock('0.3.3'))
  assert.deepEqual(checkRustNotices(lock('0.3.4'), notices), { ok: true, missing: [], extra: [] })
  assert.deepEqual(checkRustNotices(lock('1.0.0'), notices), { ok: true, missing: [], extra: [] })
})

test('the notices never list the root crate as a package', () => {
  assert.doesNotMatch(render(lock('0.3.3')), /^[-+] nq-lab-terminal /m)
})

test('the notices carry the WebView2 loader as an extra entry, outside the lockfile check', () => {
  const text = render(lock('0.3.3'))
  assert.match(text, /^\+ Microsoft WebView2 loader/m)
  assert.match(text, /Copyright \(C\) Microsoft Corporation/)
  assert.equal(WEBVIEW2_LOADER.license, 'BSD-3-Clause')
  assert.equal(checkRustNotices(lock('0.3.3'), text).ok, true)
})

function crateFolder(files, manifestExtra = {}) {
  const dir = fs.mkdtempSync(path.join(scratch, 'crate-'))
  for (const [name, body] of Object.entries(files)) fs.writeFileSync(path.join(dir, name), body)
  return { name: 'serde', version: '1.0.228', license: 'MIT OR Apache-2.0', repository: 'https://github.com/serde-rs/serde', license_file: null, manifest_path: path.join(dir, 'Cargo.toml'), ...manifestExtra }
}

test('collectCrate reads every licence file beside the manifest, as LF text, and the declared licence and repository', () => {
  const meta = crateFolder({ 'Cargo.toml': '', 'LICENSE-MIT': 'MIT text\r\n', 'LICENSE-APACHE': 'Apache text', 'README.md': 'readme' })
  const found = collectCrate(meta)
  assert.equal(found.license, 'MIT OR Apache-2.0')
  assert.equal(found.repository, 'https://github.com/serde-rs/serde')
  assert.deepEqual(found.texts, ['Apache text', 'MIT text'])
  assert.equal(found.note, '')
})

test('collectCrate reads the file a manifest names as license_file', () => {
  const meta = crateFolder({ 'Cargo.toml': '', 'TERMS.txt': 'Terms of use' }, { license: null, license_file: 'TERMS.txt' })
  const found = collectCrate(meta)
  assert.deepEqual(found.texts, ['Terms of use'])
  assert.equal(found.license, 'see the licence file')
})

test('collectCrate says so for a crate whose package holds no licence file, and keeps it in the notices', () => {
  const found = collectCrate(crateFolder({ 'Cargo.toml': '' }))
  assert.deepEqual(found.texts, [])
  assert.equal(found.note, 'no licence file in the package')
})

test('buildPackages throws for a locked crate that cargo metadata does not know, so a half-resolved tree writes nothing', () => {
  const metadata = { packages: [crateFolder({ 'Cargo.toml': '', LICENSE: 'text' }, { name: 'adler2', version: '2.0.1' })] }
  assert.throws(() => buildPackages(lockedCrates(lock('0.3.3')), metadata), /serde 1\.0\.228/)
})

test('buildPackages returns one record per locked crate, in lockfile order', () => {
  const metadata = {
    packages: [
      crateFolder({ 'Cargo.toml': '', LICENSE: 'text' }, { name: 'serde', version: '1.0.228' }),
      crateFolder({ 'Cargo.toml': '', LICENSE: 'text' }, { name: 'adler2', version: '2.0.1' }),
      crateFolder({ 'Cargo.toml': '' }, { name: 'nq-lab-terminal', version: '0.3.3', license: 'UNLICENSED' }),
    ],
  }
  assert.deepEqual(buildPackages(lockedCrates(lock('0.3.3')), metadata).map((p) => p.name), ['adler2', 'serde'])
})

test('the shipped notices file matches Cargo.lock (regenerate with: node desktop/scripts/rust-notices.mjs)', () => {
  const result = checkRustNotices(fs.readFileSync(REAL_LOCK, 'utf8'), fs.readFileSync(REAL_NOTICES, 'utf8'))
  assert.deepEqual(result, { ok: true, missing: [], extra: [] })
})

test('the shipped notices survive a version bump of the root crate in the real Cargo.lock', () => {
  const real = fs.readFileSync(REAL_LOCK, 'utf8')
  const root = /(name = "nq-lab-terminal"\r?\nversion = ")([^"]+)(")/.exec(real)
  assert.ok(root, 'the root crate entry is in the real Cargo.lock')
  const bumped = real.replace(root[0], `${root[1]}9.9.9${root[3]}`)
  assert.notEqual(bumped, real)
  assert.equal(checkRustNotices(bumped, fs.readFileSync(REAL_NOTICES, 'utf8')).ok, true)
})

test('the shipped notices name the WebView2 loader and the licences the Cargo tree uses', () => {
  const text = fs.readFileSync(REAL_NOTICES, 'utf8')
  assert.match(text, /^\+ Microsoft WebView2 loader/m)
  assert.match(text, /Mozilla Public License/)
  assert.match(text, /Apache License/)
  assert.ok(!text.includes('\r'))
  assert.match(text, /^- webview2-com-sys \S+ \| MIT/m)
})

const run = (...args) => spawnSync(process.execPath, [SCRIPT, ...args], { encoding: 'utf8' })

test('--check exits 1 and names the crate when the notices lack a locked crate', () => {
  const lockFile = path.join(scratch, 'one.lock')
  const notices = path.join(scratch, 'one.txt')
  fs.writeFileSync(lockFile, lock('0.3.3', EXTRA_CRATE))
  fs.writeFileSync(notices, render(lock('0.3.3')))
  const result = run('--check', '--lock', lockFile, '--notices', notices)
  assert.equal(result.status, 1)
  assert.match(result.stderr, /zeroize 1\.8\.1/)
})

test('--check exits 0 for matching files even after a root version bump', () => {
  const lockFile = path.join(scratch, 'ok.lock')
  const notices = path.join(scratch, 'ok.txt')
  fs.writeFileSync(lockFile, lock('0.3.9'))
  fs.writeFileSync(notices, render(lock('0.3.3')))
  assert.equal(run('--check', '--lock', lockFile, '--notices', notices).status, 0)
})

test('--check exits 2 when the notices file is missing: a check that cannot run never passes', () => {
  const lockFile = path.join(scratch, 'two.lock')
  fs.writeFileSync(lockFile, lock('0.3.3'))
  assert.equal(run('--check', '--lock', lockFile, '--notices', path.join(scratch, 'absent.txt')).status, 2)
})
