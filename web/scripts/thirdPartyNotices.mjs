// The third-party notices of the page (D7.4): web/public/third-party-notices.txt, built from web/pnpm-lock.yaml and the
// licence files each package ships, and the check that fails when the file and the lockfile no longer agree.
//
//   node scripts/thirdPartyNotices.mjs            write the notices (needs the packages installed)
//   node scripts/thirdPartyNotices.mjs --check    compare the notices with the lockfile only (no install needed)
//   options: --lock <pnpm-lock.yaml> --notices <file> --node-modules <folder>
//
//   exit 0  written, or the notices match the lockfile
//   exit 1  --check: a lockfile package is missing from the notices, or the notices name one the lockfile no longer has
//   exit 2  a file could not be read, or a package is not installed: a check that cannot run never passes
//
// "The packages the page ships" is the production closure of the lockfile: the importer's dependencies and everything their
// snapshots pull in. Dev dependencies (the test runner, the compiler) are not shipped and are left out. The renderer, the index
// parser and the licence-file reader are shared with desktop/scripts/rust-notices.mjs, which writes the same layout for the
// Cargo packages. Node built-ins only.
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { isMainModule } from './mainModule.mjs'

const WEB = fileURLToPath(new URL('..', import.meta.url))
const DEFAULT_LOCK = path.join(WEB, 'pnpm-lock.yaml')
const DEFAULT_NOTICES = path.join(WEB, 'public', 'third-party-notices.txt')
const BERGOOM_LICENCE = path.join(WEB, 'src', 'assets', 'fonts', 'bergoom', 'LICENSE.md')
const LICENCE_FILE = /^(licen[cs]e|copying|notice|unlicen[cs]e)/i
const NO_LICENCE_FILE = 'no licence file in the package'
const SECTION = { packages: 'PACKAGES', extras: 'ALSO INCLUDED', texts: 'LICENCE TEXTS' }

// ---- the layout both generators write -------------------------------------------------------------------------------

const lf = (text) => text.replace(/\r\n?/g, '\n').trimEnd()

/** The licence and notice files in a package folder, as LF text in file-name order. Empty files are skipped. */
export function collectLicenceTexts(dir) {
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && LICENCE_FILE.test(entry.name))
    .map((entry) => entry.name)
    .sort()
    .map((name) => lf(fs.readFileSync(path.join(dir, name), 'utf8')))
    .filter((text) => text.length > 0)
}

class TextTable {
  #ids = new Map()
  /** The id of a text, the same one for an identical text, so a licence used by 300 packages is printed once. */
  idFor(raw) {
    const text = lf(raw)
    const hash = createHash('sha256').update(text).digest('hex')
    if (!this.#ids.has(hash)) this.#ids.set(hash, { id: `T${this.#ids.size + 1}`, text })
    return this.#ids.get(hash).id
  }

  entries() {
    return [...this.#ids.values()]
  }
}

function packageLine(table, p) {
  const refs = p.texts.length > 0 ? p.texts.map((t) => table.idFor(t)).join(' ') : (p.note || NO_LICENCE_FILE)
  const where = p.repository ? ` | ${p.repository}` : ''
  return `- ${p.name} ${p.version} | ${p.license} | ${refs}${where}`
}

/**
 * The notices text. packages: [{ name, version, license, repository, texts, note }]; extras: [{ name, license, text }] (things the
 * lockfile does not list: a vendored font, the WebView2 loader). Only the PACKAGES lines are checked against the lockfile.
 */
export function renderNotices({ heading, source, command, packages, extras }) {
  const table = new TextTable()
  const lines = [heading, '', `Generated by ${command} from ${source}. Do not edit by hand: run it again after the lockfile changes.`, `Packages: ${packages.length}`, '', SECTION.packages]
  for (const p of packages) lines.push(packageLine(table, p))
  if (extras.length > 0) {
    lines.push('', SECTION.extras)
    for (const x of extras) lines.push(`+ ${x.name} | ${x.license} | ${table.idFor(lf(x.text))}`)
  }
  lines.push('', SECTION.texts)
  for (const { id, text } of table.entries()) lines.push('', `==== ${id} ====`, text)
  return `${lines.join('\n')}\n`
}

const PACKAGE_LINE = /^- (\S+) (\S+) \|/

/** The "name version" entries of the PACKAGES section of a notices text. */
export function parseNoticeIndex(text) {
  const lines = text.split('\n')
  const start = lines.indexOf(SECTION.packages)
  if (start < 0) return []
  const out = []
  for (const line of lines.slice(start + 1)) {
    if (line === SECTION.extras || line === SECTION.texts) break
    const m = PACKAGE_LINE.exec(line)
    if (m) out.push(`${m[1]} ${m[2]}`)
  }
  return out
}

/** The notices against the packages a lockfile lists: what is missing from the file and what it still names but the lockfile dropped. */
export function checkNotices(expected, notices) {
  const want = new Set(expected.map((p) => `${p.name} ${p.version}`))
  const have = new Set(parseNoticeIndex(notices))
  const missing = [...want].filter((k) => !have.has(k)).sort()
  const extra = [...have].filter((k) => !want.has(k)).sort()
  return { ok: missing.length === 0 && extra.length === 0, missing, extra }
}

/** The lines a failed check prints on stderr. */
export function describeMismatch({ missing, extra }, fix) {
  return [
    ...missing.map((k) => `missing from the notices: ${k}`),
    ...extra.map((k) => `in the notices but not in the lockfile: ${k}`),
    `regenerate with: ${fix}`,
  ]
}

// ---- pnpm-lock.yaml (lockfileVersion 9) -------------------------------------------------------------------------------

const unquote = (s) => s.replace(/^'(.*)'$/, '$1').replace(/^"(.*)"$/, '$1')

/** { name, version } of a lockfile key such as `@scope/pkg@1.2.3(peer@4.5.6)`: the peer suffix is not part of the version. */
function splitKey(key) {
  const bare = key.includes('(') ? key.slice(0, key.indexOf('(')) : key
  const at = bare.lastIndexOf('@')
  return { name: bare.slice(0, at), version: bare.slice(at + 1) }
}

/** The dependency key a `name: value` line points at (an alias value already carries its own name). */
function depKey(name, value) {
  const bare = value.includes('(') ? value.slice(0, value.indexOf('(')) : value
  return /^@?[^@\s]+@/.test(bare) ? value : `${name}@${value}`
}

function readImporterDeps(lines) {
  const start = lines.indexOf('  .:')
  if (start < 0) throw new Error('pnpm-lock.yaml has no root importer')
  const deps = []
  let section = ''
  let name = ''
  for (const line of lines.slice(start + 1)) {
    if (/^\S/.test(line) || /^ {2}\S/.test(line)) break
    const head = /^ {4}(\w+):$/.exec(line)
    if (head) { section = head[1]; continue }
    const dep = /^ {6}(\S.*):$/.exec(line)
    if (dep) { name = unquote(dep[1]); continue }
    const ver = /^ {8}version: (.+)$/.exec(line)
    if (ver && (section === 'dependencies' || section === 'optionalDependencies')) deps.push(depKey(name, unquote(ver[1])))
  }
  return deps
}

function readSnapshots(lines) {
  const start = lines.indexOf('snapshots:')
  const map = new Map()
  if (start < 0) return map
  let current = null
  let section = ''
  for (const line of lines.slice(start + 1)) {
    const head = /^ {2}(\S.*?):(?: \{\})?$/.exec(line)
    if (head) { current = []; map.set(unquote(head[1]), current); section = ''; continue }
    const sub = /^ {4}(\w+):$/.exec(line)
    if (sub) { section = sub[1]; continue }
    const dep = /^ {6}(\S.*?): (.+)$/.exec(line)
    if (dep && current && (section === 'dependencies' || section === 'optionalDependencies')) current.push(depKey(unquote(dep[1]), unquote(dep[2])))
  }
  return map
}

/** The packages the page ships, from the lockfile text: [{ name, version }], each once, sorted by name then version. */
export function productionPackages(lockText) {
  const lines = lockText.replace(/\r\n?/g, '\n').split('\n')
  const snapshots = readSnapshots(lines)
  const seen = new Set()
  const queue = readImporterDeps(lines).filter((k) => !/@(link|file|workspace):/.test(k))
  while (queue.length > 0) {
    const key = queue.pop()
    if (seen.has(key)) continue
    seen.add(key)
    queue.push(...(snapshots.get(key) ?? []))
  }
  const unique = new Map()
  for (const key of seen) {
    const { name, version } = splitKey(key)
    unique.set(`${name}@${version}`, { name, version })
  }
  return [...unique.values()].sort((a, b) => (a.name === b.name ? (a.version < b.version ? -1 : 1) : a.name < b.name ? -1 : 1))
}

// ---- the installed packages -------------------------------------------------------------------------------------------

/** The pnpm virtual store (the .pnpm folder) of a node_modules folder, even when its top level is only links into another one. */
export function findStore(nodeModules) {
  const direct = path.join(nodeModules, '.pnpm')
  if (fs.existsSync(direct)) return direct
  if (!fs.existsSync(nodeModules)) return null
  for (const entry of fs.readdirSync(nodeModules, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || entry.name.startsWith('@')) continue
    const real = fs.realpathSync(path.join(nodeModules, entry.name)).split(path.sep)
    const at = real.lastIndexOf('.pnpm')
    if (at > 0) return real.slice(0, at + 1).join(path.sep)
  }
  return null
}

function normaliseRepository(repo) {
  const url = typeof repo === 'string' ? repo : repo?.url
  if (!url) return ''
  const github = /^github:(.+)$/.exec(url)
  if (github) return `https://github.com/${github[1]}`
  return url.replace(/^git\+/, '').replace(/^git:\/\//, 'https://').replace(/^ssh:\/\/git@/, 'https://').replace(/\.git$/, '')
}

function declaredLicence(manifest) {
  if (typeof manifest.license === 'string') return manifest.license
  if (manifest.license?.type) return manifest.license.type
  if (Array.isArray(manifest.licenses)) return manifest.licenses.map((l) => (typeof l === 'string' ? l : l.type)).join(' OR ')
  return 'not declared'
}

/** The folder of an installed package in the store. Throws when it is not there: half a notices file is worse than none. */
function packageDir(store, { name, version }) {
  const prefix = `${name.replace('/', '+')}@${version}`
  const entries = fs.readdirSync(store).sort()
  // pnpm shortens a long folder name to its first characters plus an underscore and a hash, so a name with a long peer list is
  // found by prefix in either direction, and the folder's own package.json confirms which package it holds.
  const candidates = entries.filter((n) => n === prefix || n.startsWith(`${prefix}_`)
    || (/_[0-9a-f]{32}$/.test(n) && (prefix.startsWith(n.slice(0, -33)) || n.slice(0, -33).startsWith(prefix))))
  for (const entry of candidates) {
    const dir = path.join(store, entry, 'node_modules', ...name.split('/'))
    const manifest = path.join(dir, 'package.json')
    if (fs.existsSync(manifest) && JSON.parse(fs.readFileSync(manifest, 'utf8')).version === version) return dir
  }
  throw new Error(`${name}@${version} is not installed under ${store}`)
}

/** A package's notice record: declared licence, repository and the texts of its licence files. */
export function collectPackage(store, pkg) {
  const dir = packageDir(store, pkg)
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
  const texts = collectLicenceTexts(dir)
  return { ...pkg, license: declaredLicence(manifest), repository: normaliseRepository(manifest.repository), texts, note: texts.length > 0 ? '' : NO_LICENCE_FILE }
}

// ---- command line -----------------------------------------------------------------------------------------------------

function parseArgs(argv) {
  const opts = { check: false, lock: DEFAULT_LOCK, notices: DEFAULT_NOTICES, nodeModules: path.join(WEB, 'node_modules') }
  const names = { '--lock': 'lock', '--notices': 'notices', '--node-modules': 'nodeModules' }
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--check') opts.check = true
    else if (names[argv[i]] && argv[i + 1] !== undefined) opts[names[argv[i]]] = path.resolve(argv[++i])
    else throw new Error(`unknown argument: ${argv[i]}`)
  }
  return opts
}

export function generate({ lock, notices, nodeModules }) {
  const store = findStore(nodeModules)
  if (!store) throw new Error(`no pnpm store under ${nodeModules}: install the packages first (pnpm install), then run this again`)
  const packages = productionPackages(fs.readFileSync(lock, 'utf8')).map((p) => collectPackage(store, p))
  const text = renderNotices({
    heading: 'Third-party notices: nq-lab terminal, page libraries (npm)',
    source: 'web/pnpm-lock.yaml (production packages)',
    command: 'pnpm --dir web notices',
    packages,
    extras: [{ name: 'Bergoom font (web/src/assets/fonts/bergoom)', license: 'OFL-1.1', text: fs.readFileSync(BERGOOM_LICENCE, 'utf8') }],
  })
  fs.writeFileSync(notices, text)
  return packages.length
}

export function main(argv = process.argv.slice(2)) {
  try {
    const opts = parseArgs(argv)
    if (!opts.check) {
      console.log(`wrote ${path.relative(process.cwd(), opts.notices)}: ${generate(opts)} packages`)
      return 0
    }
    const result = checkNotices(productionPackages(fs.readFileSync(opts.lock, 'utf8')), fs.readFileSync(opts.notices, 'utf8'))
    if (!result.ok) {
      console.error(describeMismatch(result, 'pnpm --dir web notices').join('\n'))
      return 1
    }
    console.log('third-party notices match pnpm-lock.yaml')
    return 0
  } catch (error) {
    console.error(`thirdPartyNotices: ${error instanceof Error ? error.message : String(error)}`)
    return 2
  }
}

if (isMainModule(import.meta.url)) process.exitCode = main()
